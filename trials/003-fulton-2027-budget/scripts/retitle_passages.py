#!/usr/bin/env python3
"""Replace the header that trials/tools/build_passages.py hard-codes ("# Passages: Trial 001 (HB 1009)").

Usage: python3 -I trials/003-fulton-2027-budget/scripts/retitle_passages.py trials/003-fulton-2027-budget/passages.md

Changes only the lines before the first '### P-' heading, and checks that nothing after it changed.
Needed until build_passages.py takes its title from the spec (see log.md, tool changes).
"""
import sys
from pathlib import Path

HEADER = """# Passages: Trial 003 (Fulton County 2027 budget)

Generated by `trials/tools/build_passages.py` from `passages.spec.yaml`. Each passage is an exact
span of a hashed snapshot listed in [sources.yaml](sources.yaml), or of a text file derived from one
(see the comments at the top of the spec). Passages from the county code use the **as-adopted** text
(struck words removed, underlined words kept), recovered with `trials/tools/pdf_markup.py`.
This header was replaced by `scripts/retitle_passages.py`; the passages below are untouched.

"""

path = Path(sys.argv[1])
text = path.read_text(encoding="utf-8")
cut = text.index("### P-")
body = text[cut:]
path.write_text(HEADER + body, encoding="utf-8")
assert path.read_text(encoding="utf-8")[len(HEADER):] == body
print(f"retitled {path}; {body.count('### P-')} passages unchanged")
