#!/usr/bin/env python3
"""The desk: what exists, what changed and what needs doing next, so nobody keeps track by memory.

    desk.py index                     one row per page -> trials/registry.json, a printed table, and the table in trials/README.md
    desk.py watch [--fetch] [TRIAL]   re-check each watched source against our copy -> TRIAL/watch.json
    desk.py watch --accept TRIAL SID  after a revision: take the source's new text as the baseline
    desk.py queue                     everything that needs work, soonest first -> trials/queue.json and a printed list
    desk.py impact TRIAL SID|P-NNN    the passages a source holds and the sentences that cite them
    desk.py brief TRIAL               a one-screen card for an agent: state, what is due, and a map of the files

Options: --root DIR (default: the trials/ folder this script sits in) and --today YYYY-MM-DD (for tests).

A page declares what would make it stale in page.yaml:

    stage: open            # open | decided
    watch:
      sources: [S01, {id: S04, only: "57171"}, {id: S09, ignore: "^Last updated"}]   # listing pages to re-check
      #   only:   keep just the lines that match (our docket's rows on a busy calendar)
      #   ignore: drop the lines that match (a "last updated" stamp)
      events:
        - {date: 2026-12-02, what: "Briefs due. Add each party's final position."}   # add `done: true` when handled

What puts work on the queue (all found by code, never by a model):
  1 date-passed     a dated item under "Coming up" or "Act now" whose date has passed
  2 source-changed  a watched source whose visible text no longer matches our baseline
  3 event           a declared event due within 7 days, or overdue
  4 check           sentences waiting for a check, or flagged
  5 old             an open page not revised for more than 14 days
  6 notes           fairness notes left open (never blocks)

Needs PyYAML. `watch --fetch` also needs httpx and beautifulsoup4 (the same as snapshot.py). A fetched page is
untrusted data: this tool hashes and diffs it, and never acts on what it says.
"""
from __future__ import annotations

import datetime as dt
import difflib
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).parent))
from ledger import FLAG, current, load_ledger  # noqa: E402
from render_prototype import iso_date, parse_passages  # noqa: E402

DUE_SOON, OLD_AFTER = 7, 14
NORM = 3   # raise when the way text is made comparable changes, so every baseline is rebuilt from our saved copy
RULES = ["date-passed", "source-changed", "event", "check", "old", "notes"]
START, END = "<!-- desk:index:start (generated by trials/tools/desk.py index; do not edit) -->", "<!-- desk:index:end -->"


# ---------- reading a page ----------

def trial_dirs(root: Path) -> list[Path]:
    return sorted(p.parent for p in root.glob("*/page.yaml"))


def find_trial(root: Path, name: str) -> Path:
    for t in trial_dirs(root):
        cfg = yaml.safe_load((t / "page.yaml").read_text(encoding="utf-8")) or {}
        if name in (t.name, str(t), cfg.get("slug")) or t.name.startswith(name) or Path(name).resolve() == t.resolve():
            return t
    sys.exit(f"no page matches {name!r} under {root}")


def cfg_of(trial: Path) -> dict:
    return yaml.safe_load((trial / "page.yaml").read_text(encoding="utf-8")) or {}


def sources_of(trial: Path) -> dict[str, dict]:
    """Every source entry in sources.yaml, wherever it is nested: a mapping with an `id` like S01 or S04b."""
    out: dict[str, dict] = {}

    def walk(x):
        if isinstance(x, dict):
            if re.fullmatch(r"S\d+[a-z]?", str(x.get("id", ""))):
                out.setdefault(x["id"], x)
            for v in x.values():
                walk(v)
        elif isinstance(x, list):
            for v in x:
                walk(v)

    f = trial / "sources.yaml"
    if f.exists():
        walk(yaml.safe_load(f.read_text(encoding="utf-8")))
    return out


def revision_of(trial: Path) -> str | None:
    f = trial / "workspace.md"
    if not f.exists():
        return None
    m = re.search(r"revision (\d+(?:\.\d+)?)", "\n".join(f.read_text(encoding="utf-8").splitlines()[:6]))
    return m.group(1) if m else None


def last_revised(trial: Path) -> str | None:
    """The date of the newest line in revisions.jsonl, else the last commit that touched the page."""
    f = trial / "revisions.jsonl"
    if f.exists():
        rows = [json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()]
        if rows:
            return max(r.get("date", "") for r in rows) or None
    r = subprocess.run(["git", "log", "-1", "--format=%cs", "--", "workspace.md"], cwd=trial, capture_output=True, text=True)
    return r.stdout.strip() or None


def dated_items(trial: Path) -> list[dict]:
    """Dated bullets under a "Coming up" or "Act now" heading in home.md and workspace.md, with file and line."""
    out = []
    for name in ("home.md", "workspace.md"):
        f = trial / name
        if not f.exists():
            continue
        head = ""
        for no, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
            if line.startswith("#"):
                head = line.lstrip("#").strip().lower()
            m = re.match(r"^\s*-\s+\*\*(.+?):\*\*\s*(.*)$", line)
            if m and re.match(r"(coming up|act now)", head):
                date = iso_date(m.group(1))
                if date:
                    out.append({"file": name, "line": no, "section": head, "when": m.group(1), "date": date, "text": m.group(2)[:120]})
    return out


def ledger_counts(trial: Path) -> dict:
    """Sentence counts without rewriting claims.jsonl."""
    try:
        store, rows = load_ledger(trial), current(trial)
    except FileNotFoundError:
        return {"units": 0, "pending": 0, "flagged": 0}
    verdicts = [(store.get(u["key"]) or {}).get("verdict") for u in rows]
    return {"units": len(rows), "pending": sum(1 for v in verdicts if not v), "flagged": sum(1 for v in verdicts if v in FLAG)}


def status_of(trial: Path) -> dict:
    f = trial / "status.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}


# ---------- index ----------

def row_of(trial: Path, today: str) -> dict:
    cfg, st, led = cfg_of(trial), status_of(trial), ledger_counts(trial)
    srcs = sources_of(trial)
    nxt = sorted(d["date"] for d in dated_items(trial) if d["date"] >= today)
    passages = parse_passages(trial / "passages.md") if (trial / "passages.md").exists() else {}
    fair = st.get("fairness") or {}
    gate = st.get("gate") or {}
    gate_ok = bool(gate) and all(v.get("pass") for v in gate.values() if isinstance(v, dict))
    current_status = st.get("revision") == revision_of(trial)
    return {
        "trial": trial.name, "slug": cfg.get("slug"), "topic": cfg.get("topic") or "", "kind": cfg.get("kind"),
        "stage": cfg.get("stage") or "open", "publish": cfg.get("publish", True), "title": cfg.get("title"),
        "revision": revision_of(trial), "last_revised": last_revised(trial),
        "passed_checks": bool(gate_ok and current_status and not led["pending"] and not led["flagged"] and not fair.get("high")),
        "status_current": current_status, "gate_pass": gate_ok,
        "sentences": led["units"], "pending": led["pending"], "flagged": led["flagged"],
        "sources": sum(1 for s in srcs.values() if s.get("status") == "retrieved"), "passages": len(passages),
        "open_notes": len(fair.get("open_items") or []), "next_date": nxt[0] if nxt else None,
        "watched": len((cfg.get("watch") or {}).get("sources") or []),
    }


def table(rows: list[dict]) -> str:
    head = "| Page | Topic | Stage | Revision | Checks | Sentences | Sources | Next date | Open notes |\n|---|---|---|---|---|---|---|---|---|\n"
    body = ""
    for r in rows:
        checks = "Passed" if r["passed_checks"] else (
            f"{r['pending'] + r['flagged']} sentences waiting" if r["pending"] or r["flagged"] else
            "Status out of date: run status.py" if not r["status_current"] else "Gate failing")
        body += (f"| [{r['trial'][:3]}]({r['trial']}/) {r['slug']} | {r['topic']} | {r['stage']} | {r['revision']} "
                 f"({r['last_revised'] or '?'}) | {checks} | {r['sentences']} | {r['sources']} | {r['next_date'] or 'none'} | {r['open_notes']} |\n")
    return head + body


def index(root: Path, today: str, refresh: bool = True) -> list[dict]:
    if refresh:
        from status import status as write_status   # runs the gate for each page, so the table is never stale
        for t in trial_dirs(root):
            if (t / "workspace.md").exists():
                write_status(t)
    rows = [row_of(t, today) for t in trial_dirs(root)]
    (root / "registry.json").write_text(json.dumps({"generated": today, "pages": rows}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    readme = root / "README.md"
    if readme.exists():
        text = readme.read_text(encoding="utf-8")
        if START in text and END in text:
            a, b = text.index(START) + len(START), text.index(END)
            readme.write_text(text[:a] + "\n" + table(rows) + text[b:], encoding="utf-8")
    return rows


# ---------- watch ----------

def norm_text(text: str, ignore: str | None = None, only: str | None = None) -> str:
    """One trimmed line per line. `ignore` drops matching lines (a "last updated" stamp); `only` keeps just the
    matching lines (our docket's rows on a calendar whose sidebar of upcoming events rolls every week)."""
    lines = []
    for ln in text.splitlines():
        ln = re.sub(r"\s+", " ", ln).strip()
        if ln and not (ignore and re.search(ignore, ln)) and (not only or re.search(only, ln)):
            lines.append(ln)
    if only:   # the kept rows, whatever their order or however many times the page repeats them
        lines = sorted(set(lines))
    return "\n".join(lines)


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def compare(old: str, new: str) -> tuple[dict, str]:
    """What changed between two texts: the counts (safe to commit), and the changed lines themselves, which are
    source text and stay in the git-ignored _raw/ folder. Changed lines are data, never instructions."""
    a, b = old.splitlines(), new.splitlines()
    sa, sb = set(a), set(b)
    added, removed = [x for x in b if x not in sa], [x for x in a if x not in sb]
    detail = "\n".join([f"+ {x[:300]}" for x in added] + [f"- {x[:300]}" for x in removed])
    return {"added": len(added), "removed": len(removed)}, detail


def watched(cfg: dict) -> list[dict]:
    return [x if isinstance(x, dict) else {"id": x} for x in (cfg.get("watch") or {}).get("sources") or []]


def http_fetch(url: str) -> tuple[int, str, bytes]:
    import httpx
    from snapshot import UA
    with httpx.Client(follow_redirects=True, timeout=60, headers={"User-Agent": UA}) as client:
        r = client.get(url)
    return r.status_code, r.headers.get("content-type", "").split(";")[0].strip().lower(), r.content


FIRST_KEYS = ("filedDate", "date", "EventDate", "MatterIntroDate", "description", "title", "name", "MatterTitle", "EventBodyName")


def json_lines(obj, prefix: str = "") -> list[str]:
    """One line per list item or scalar, so a new filing in a list shows up as one added line."""
    if isinstance(obj, dict):
        out = []
        for k in sorted(obj):
            out += json_lines(obj[k], f"{prefix}{k}.")
        return out
    if isinstance(obj, list):
        out = []
        for item in obj:
            if isinstance(item, dict):   # the item's own plain fields; nested contact blocks churn without meaning
                keys = [k for k in FIRST_KEYS if k in item] + sorted(k for k in item if k not in FIRST_KEYS)
                keys = [k for k in keys if not isinstance(item[k], (dict, list))]
                out.append(f"{prefix}[] " + " | ".join(f"{k}={json.dumps(item[k], ensure_ascii=False)}" for k in keys))
            else:
                out.append(f"{prefix}[] {json.dumps(item, ensure_ascii=False)}")
        return out
    return [f"{prefix.rstrip('.')}: {json.dumps(obj, ensure_ascii=False)}"]


def text_of(body: bytes) -> str:
    """Comparable text for a saved or fetched body, judged by what it is, not by the content type the server
    claims (the PSC serves its JSON filing list as text/html)."""
    head = body[:2000].lstrip().lower()
    if head[:1] in (b"{", b"["):
        try:
            return "\n".join(json_lines(json.loads(body.decode("utf-8", "replace"))))
        except ValueError:
            pass
    if re.search(rb"<(html|!doctype html|body|div|p|table|h[1-6]|ul|span|a)\b", head):
        from snapshot import visible_text
        return visible_text(body)
    if b"\x00" not in body[:2000] and not head.startswith(b"%pdf"):
        return body.decode("utf-8", "replace")
    return "sha256:" + hashlib.sha256(body).hexdigest()   # a PDF or other file: compare its bytes


def saved_body(trial: Path, sid: str) -> bytes | None:
    """Our snapshot's exact bytes: _raw/SID.<ext>, not the derived .txt or the headers file."""
    for f in sorted((trial / "_raw").glob(f"{sid}.*")):
        if f.name.count(".") == 1 and f.suffix != ".txt":
            return f.read_bytes()
    return None


def load_watch(trial: Path) -> dict:
    f = trial / "watch.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {"sources": {}}


def watch_check(trial: Path, now: str, fetch=http_fetch) -> dict:
    """Fetch each watched source and compare its visible text with the baseline. The first baseline is our saved
    copy (_raw/SID.txt) when we have it, so a change since the snapshot is caught; otherwise it is this fetch."""
    cfg, srcs, state = cfg_of(trial), sources_of(trial), load_watch(trial)
    for w in watched(cfg):
        sid, rec = w["id"], state["sources"].setdefault(w["id"], {})
        url = (srcs.get(sid) or {}).get("url")
        rec.update(url=url, last_checked=now, checks=rec.get("checks", 0) + 1)
        if not url:
            rec.update(state="blocked", note="no url in sources.yaml")
            continue
        try:
            code, ctype, body = fetch(url)
        except Exception as e:   # noqa: BLE001  network errors are recorded, not raised
            rec.update(state="blocked", note=f"{type(e).__name__}: {str(e)[:120]}")
            continue
        if code != 200 or not body:
            rec.update(state="blocked", http_status=code, note="not 200, or an empty body")
            continue
        rule = {"ignore": w.get("ignore"), "only": w.get("only"), "norm": NORM}
        keep = {"ignore": rule["ignore"], "only": rule["only"]}
        new = norm_text(text_of(body), **keep)
        wdir = trial / "_raw" / "watch"
        wdir.mkdir(parents=True, exist_ok=True)
        base = wdir / f"{sid}.base.txt"
        if rec.get("rule") != rule or "text_sha256" not in rec or not base.exists():   # first check, or the rule changed
            saved = saved_body(trial, sid)
            old = norm_text(text_of(saved), **keep) if saved else new
            base.write_text(old, encoding="utf-8")
            rec.update(rule=rule, text_sha256=digest(old), baseline="our saved copy" if saved else "first fetch",
                       baseline_at=(srcs[sid].get("retrieved_at") or now) if saved else now)
        rec["http_status"] = code
        for k in ("diff", "new_text_sha256", "note"):
            rec.pop(k, None)
        if digest(new) == rec["text_sha256"]:
            rec.update(state="unchanged")
            continue
        counts, detail = compare(base.read_text(encoding="utf-8"), new)
        (wdir / f"{sid}.new.txt").write_text(new, encoding="utf-8")
        (wdir / f"{sid}.diff.txt").write_text(detail + "\n", encoding="utf-8")
        rec.update(changes=rec.get("changes", 0) + (rec.get("state") != "changed"), state="changed", new_text_sha256=digest(new), diff=counts)
    state["checked"] = now
    (trial / "watch.json").write_text(json.dumps(state, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return state


def watch_accept(trial: Path, sid: str, now: str) -> None:
    state = load_watch(trial)
    rec = state["sources"].get(sid)
    if not rec or rec.get("state") != "changed":
        sys.exit(f"{sid} has no recorded change to accept")
    new = trial / "_raw" / "watch" / f"{sid}.new.txt"
    if not new.exists():
        sys.exit(f"the fetched text for {sid} is gone (a new container?): run `desk.py watch --fetch` first")
    new.replace(trial / "_raw" / "watch" / f"{sid}.base.txt")
    rec.update(text_sha256=rec.pop("new_text_sha256"), baseline_at=now, baseline="accepted after a revision", state="unchanged")
    rec.pop("diff", None)
    (trial / "watch.json").write_text(json.dumps(state, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


# ---------- impact ----------

def impact(trial: Path, ref: str) -> dict:
    passages = parse_passages(trial / "passages.md")
    pids = [ref] if ref.startswith("P-") else sorted(p for p, v in passages.items() if v["source"] == ref)
    hits = [u for u in current(trial) if set(u["passages"]) & set(pids)]
    return {"ref": ref, "passages": pids, "sentences": [{"file": u["file"], "line": u["line"], "cites": [p for p in u["passages"] if p in pids],
                                                          "sentence": u["sentence"][:140]} for u in hits]}


# ---------- queue ----------

def queue(root: Path, today: str) -> list[dict]:
    t0, items = dt.date.fromisoformat(today), []
    for trial in trial_dirs(root):
        cfg, led, st = cfg_of(trial), ledger_counts(trial), status_of(trial)
        slug, stage = cfg.get("slug"), cfg.get("stage") or "open"

        def add(rule, due, what, where="", size=""):
            items.append({"trial": trial.name, "slug": slug, "rule": rule, "due": due, "what": what, "where": where, "size": size})

        for d in dated_items(trial):
            if d["date"] < today:
                add("date-passed", d["date"], f"\"{d['when']}\" has passed: move it to What happened, with the outcome if a source gives one",
                    f"{d['file']}:{d['line']}", "patch, then a pair check (Sonnet)")
        for sid, rec in (load_watch(trial).get("sources") or {}).items():
            if rec.get("state") == "changed":
                n = len(impact(trial, sid)["sentences"])
                diff = rec.get("diff") or {}
                add("source-changed", (rec.get("last_checked") or today)[:10],
                    f"{sid} changed ({diff.get('added', '?')} added, {diff.get('removed', '?')} removed): snapshot it again and revise what it touches",
                    f"desk.py impact {trial.name} {sid}", f"{n} sentences cite it")
            elif rec.get("state") == "blocked":
                add("source-changed", (rec.get("last_checked") or today)[:10], f"{sid} could not be re-checked ({rec.get('note', '')})", "", "record as blocked")
        for ev in (cfg.get("watch") or {}).get("events") or []:
            if ev.get("done"):
                continue
            due = str(ev["date"])
            if (dt.date.fromisoformat(due) - t0).days <= DUE_SOON:
                add("event", due, ev["what"], "page.yaml watch.events", "revision (at most 100k)")
        if led["pending"] or led["flagged"]:
            add("check", today, f"{led['pending']} sentences waiting for a check, {led['flagged']} flagged",
                f"ledger.py pending {trial.name}", "pair check (Sonnet)")
        rev = last_revised(trial)
        if stage == "open" and rev and (t0 - dt.date.fromisoformat(rev)).days > OLD_AFTER:
            add("old", rev, f"open page last revised {rev}: check its watched sources", "", "watch --fetch")
        notes = len((st.get("fairness") or {}).get("open_items") or [])
        if notes:
            add("notes", "9999-12-31", f"{notes} fairness notes left open", f"{trial.name}/status.json", "optional")
    items.sort(key=lambda i: (i["rule"] == "notes", i["due"], RULES.index(i["rule"])))
    (root / "queue.json").write_text(json.dumps({"generated": today, "items": items}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return items


# ---------- brief ----------

def brief(root: Path, trial: Path, today: str) -> str:
    cfg, r = cfg_of(trial), row_of(trial, today)
    out = [f"{trial.name} · {cfg.get('slug')} · {cfg.get('topic') or ''}", f"\"{cfg.get('title')}\"",
           f"Stage {r['stage']} · revision {r['revision']} (last revised {r['last_revised'] or '?'}) · "
           + ("passed checks" if r["passed_checks"] else f"{r['pending']} pending, {r['flagged']} flagged")
           + f" · {r['sentences']} sentences, {r['passages']} passages, {r['sources']} sources · next date {r['next_date'] or 'none'}", ""]
    mine = [i for i in queue(root, today) if i["trial"] == trial.name]
    out.append("Due:" if mine else "Due: nothing")
    out += [f"  [{i['rule']}] {i['due'] if i['due'] < '9999' else '-'}  {i['what']}" + (f"  ({i['where']})" if i["where"] else "") for i in mine]
    ws = load_watch(trial).get("sources") or {}
    if watched(cfg):
        out.append("Watched sources: " + ", ".join(f"{w['id']} {ws.get(w['id'], {}).get('state', 'never checked')}" for w in watched(cfg)))
    evs = [e for e in (cfg.get("watch") or {}).get("events") or [] if not e.get("done")]
    if evs:
        out.append("Events ahead: " + "; ".join(f"{e['date']} {e['what']}" for e in evs))
    out.append("")
    out.append("Files (read only the lines you change):")
    for name in ("workspace.md", "home.md"):
        f = trial / name
        if not f.exists():
            continue
        lines = f.read_text(encoding="utf-8").splitlines()
        heads = [(no, ln) for no, ln in enumerate(lines, 1) if ln.startswith("## ") or ln.startswith("### ")]
        out.append(f"  {name} ({len(lines)} lines)")
        for k, (no, ln) in enumerate(heads):
            end = heads[k + 1][0] - 1 if k + 1 < len(heads) else len(lines)
            out.append(f"    L{no}-{end}  {'  ' if ln.startswith('### ') else ''}{ln.lstrip('# ')[:70]}")
    out.append(f"  page.yaml (display settings, pictures, watch list) · passages.md ({r['passages']} passages) · sources.yaml")
    out.append("")
    out.append("Rules: docs/process/drafter-card.md. A fix is a patch. After a change: status.py, then judge.py on the pending sentences.")
    return "\n".join(out)


# ---------- command line ----------

def main(argv: list[str]) -> int:
    def opt(name, default=None):
        if name in argv:
            i = argv.index(name)
            value = argv[i + 1]
            del argv[i:i + 2]
            return value
        return default

    root = Path(opt("--root", str(Path(__file__).resolve().parent.parent)))
    today = opt("--today", dt.date.today().isoformat())
    fetch = "--fetch" in argv
    accept = "--accept" in argv
    no_refresh = "--no-refresh" in argv
    argv = [a for a in argv if a not in ("--fetch", "--accept", "--no-refresh")]
    if not argv or argv[0] not in ("index", "watch", "queue", "impact", "brief"):
        sys.exit(__doc__)
    cmd, args = argv[0], argv[1:]
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    if cmd == "index":
        print(table(index(root, today, refresh=not no_refresh)))
    elif cmd == "watch":
        if accept:
            watch_accept(find_trial(root, args[0]), args[1], now)
            return 0
        for t in ([find_trial(root, args[0])] if args else trial_dirs(root)):
            state = watch_check(t, now) if fetch else load_watch(t)
            for sid, rec in (state.get("sources") or {}).items():
                d = rec.get("diff") or {}
                extra = f" (+{d.get('added')} -{d.get('removed')} lines)" if rec.get("state") == "changed" and d else f" ({rec['note']})" if rec.get("state") == "blocked" else ""
                print(f"{t.name} {sid}: {rec.get('state', 'never checked')}{extra}; checked {rec.get('last_checked', 'never')}")
                detail = t / "_raw" / "watch" / f"{sid}.diff.txt"
                if rec.get("state") == "changed" and detail.exists():
                    for ln in detail.read_text(encoding="utf-8").splitlines()[:6]:
                        print(f"    {ln[:170]}")
            if not state.get("sources"):
                print(f"{t.name}: no watched sources" + ("" if watched(cfg_of(t)) else " declared in page.yaml"))
    elif cmd == "queue":
        items = queue(root, today)
        print(f"{len(items)} items, as of {today}")
        for i in items:
            print(f"  {i['due'] if i['due'] < '9999' else '   -      '}  {i['slug']:<20} [{i['rule']}] {i['what']}"
                  + (f"\n{'':14}where: {i['where']}" if i["where"] else "") + (f" · {i['size']}" if i["size"] else ""))
    elif cmd == "impact":
        res = impact(find_trial(root, args[0]), args[1])
        print(f"{res['ref']}: {len(res['passages'])} passages, cited by {len(res['sentences'])} sentences")
        for s in res["sentences"]:
            print(f"  {s['file']}:{s['line']} [{', '.join(s['cites'])}] {s['sentence']}")
    elif cmd == "brief":
        print(brief(root, find_trial(root, args[0]), today))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
