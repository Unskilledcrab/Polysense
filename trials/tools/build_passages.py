#!/usr/bin/env python3
"""Build passages.md from a hand-written spec, copying exact spans from snapshot text files.

Usage:
    uv run --with pyyaml python3 trials/tools/build_passages.py trials/001-*/passages.spec.yaml

The spec is the manual part: a person (or agent) chooses each passage by naming the source,
a locator, and the exact first and last words of the span. This script only copies the text between
them, so passages can't drift from the snapshot by hand-typing errors.

Spec entry:
  - id: P-006
    source: S01                      # id in sources.yaml
    file: hb1009-247117.clean.txt    # in _raw/
    locator: "p.3, lines 42-44"
    start: "(2) Beginning no later"
    end: "required by law."
    fix: [["old", "new"]]            # optional, only for extraction glitches; always add a note
    note: "why the fix was needed"

Bill text files made by pdf_markup.py have "pN: LINE " prefixes, which are removed before matching.
Whitespace is normalized to single spaces. Fails loudly if a start/end string is not found.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("needs PyYAML: uv run --with pyyaml python3 trials/tools/build_passages.py ...")

PREFIX = re.compile(r"^p\d+:\s+(?:\d+\s+)?", re.M)


def load(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    text = PREFIX.sub("", text)
    return re.sub(r"\s+", " ", text)


def main(spec_path: Path) -> int:
    trial = spec_path.parent
    raw = trial / "_raw"
    spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
    cache: dict[str, str] = {}
    out = [
        "# Passages: Trial 001 (HB 1009)",
        "",
        "Generated by `trials/tools/build_passages.py` from `passages.spec.yaml`. Each passage is an exact",
        "span of a hashed snapshot listed in [sources.yaml](sources.yaml). Bill passages use the **as-enacted**",
        "text (struck words removed, underlined words kept), recovered with `trials/tools/pdf_markup.py`.",
        "",
    ]
    errors = 0
    for p in spec["passages"]:
        if p["file"] not in cache:
            cache[p["file"]] = load(raw / p["file"])
        text = cache[p["file"]]
        i = text.find(p["start"])
        j = text.find(p["end"], i if i >= 0 else 0)
        if i < 0 or j < 0:
            print(f"NOT FOUND {p['id']}: start={i >= 0} end={j >= 0}", file=sys.stderr)
            errors += 1
            continue
        span = text[i : j + len(p["end"])].strip()
        for old, new in p.get("fix", []) or []:
            if old not in span:
                print(f"FIX NOT APPLICABLE {p['id']}: {old!r}", file=sys.stderr)
                errors += 1
            span = span.replace(old, new)
        out.append(f"### {p['id']} · {p['source']} · {p['locator']}")
        out.append(f"> {span}")
        if p.get("note"):
            out.append("")
            out.append(f"*Note: {p['note']}*")
        out.append("")
    (trial / "passages.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {len(spec['passages']) - errors} passages; {errors} errors")
    return 1 if errors else 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(Path(sys.argv[1])))
